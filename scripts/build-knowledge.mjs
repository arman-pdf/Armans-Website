// Builds functions/_knowledge.js: the ONLY facts the assistant may use.
// Source of truth is src/projects.json (imported from PORTFOLIO_PROJECTS.md).
// Exports INDEX (one compact line per project, always sent) and NOTES (full write-ups;
// only the few most relevant to a question are sent, to stay inside free-tier token limits).
import { readFileSync, writeFileSync } from 'node:fs';

const projects = JSON.parse(readFileSync(new URL('../src/projects.json', import.meta.url), 'utf8'));

const bullets = (items) =>
  items.map((i) => `- ${i.text}${i.sub.length ? '\n' + i.sub.map((s) => `  - ${s}`).join('\n') : ''}`).join('\n');
const who = (p) => (p.team ? `Team: ${p.team}` : p.role ? `Role: ${p.role}` : '');

const INDEX = projects
  .map((p) => `- ${p.title} [/projects/${p.slug}] (${p.year}; ${p.team || p.role}; topics: ${p.tags.join(', ')}; tools: ${p.tools})`)
  .join('\n');

const NOTES = projects.map((p) => ({
  slug: p.slug,
  title: p.title,
  tags: p.tags.join(' '),
  tools: p.tools,
  body: `${p.tagline} ${p.overview} ${p.did.map((d) => d.text).join(' ')} ${p.outcomes.map((o) => `${o.text} ${o.sub.join(' ')}`).join(' ')}`,
  text: [
    `## ${p.title}`,
    `Page: /projects/${p.slug}`,
    `Academic year: ${p.year}. ${p.context}`,
    who(p),
    `Topics: ${p.tags.join(', ')}`,
    `Tools and methods: ${p.tools}`,
    `Overview: ${p.overview}`,
    `What Arman did:\n${bullets(p.did)}`,
    `Outcomes:\n${bullets(p.outcomes)}`,
    p.related ? `Related co-op work: ${p.related}` : '',
  ].filter(Boolean).join('\n'),
}));

writeFileSync(
  new URL('../functions/_knowledge.js', import.meta.url),
  `// GENERATED by scripts/build-knowledge.mjs. Do not edit.\nexport const INDEX = ${JSON.stringify(INDEX)};\nexport const NOTES = ${JSON.stringify(NOTES)};\n`
);
console.log(`knowledge: ${projects.length} projects; index ~${Math.round(INDEX.length / 4)} tokens; full notes ~${Math.round(NOTES.reduce((n, x) => n + x.text.length, 0) / 4)} tokens`);
